export const translateFleetText = (text: string, language: string): string => {
  const lang = language.slice(0, 2);
  if (lang !== 'en' && lang !== 'fr') return text;
  return FLEET_TEXT[lang][text] ?? text;
};

/** Devolve uma função que traduz textos de dados da frota para o idioma activo. */
export const useFleetText = () => {
  const { i18n } = useTranslation();
  const language = i18n.resolvedLanguage ?? i18n.language ?? 'pt';
  return useCallback((text: string | undefined) => (text ? translateFleetText(text, language) : ''), [language]);
};
