// Formata o catálogo detalhado para o prompt com todas as especificações exatas.
export function fleetCatalogText(catalog) {
  const groups = new Map();
  for (const v of catalog) {
    if (!groups.has(v.categoryLabel)) groups.set(v.categoryLabel, []);
    groups.get(v.categoryLabel).push(v);
  }
  return [...groups.entries()]
    .map(([label, list]) => {
      const rows = list
        .map((v) => {
          const parts = [`- ${v.name}:`];
          parts.push(`${v.seats} lugares, ${v.doors} portas`);
          if (v.luggage) parts.push(`${v.luggage} malas`);
          if (v.transmission) parts.push(`Câmbio: ${v.transmission}`);
          if (v.fuel) parts.push(`Combustível: ${v.fuel}${v.tankCapacity ? ` (${v.tankCapacity})` : ''}`);
          if (v.traction) parts.push(`Tracção: ${v.traction}`);
          if (v.engine) parts.push(`Motor: ${v.engine}`);
          parts.push(`· Diária: ${v.pricePerDay} Kz · Transfer: ${v.transferPrice} Kz`);
          if (v.deposit) parts.push(`· Caução: ${v.deposit}`);
          return parts.join(' ');
        })
        .join('\n');
      return `## ${label}\n${rows}`;
    })
    .join('\n\n');
}
